"""Optional browser QA. Run against a built dist directory with Playwright and Chromium."""
import os
from pathlib import Path
from tempfile import TemporaryDirectory

from playwright.sync_api import expect, sync_playwright

base = os.getenv("ATLAS_TEST_URL", "http://127.0.0.1:8765").rstrip("/")
with sync_playwright() as p, TemporaryDirectory() as tmp:
    browser = p.chromium.launch(executable_path=os.getenv("ATLAS_CHROMIUM") or None, args=["--no-sandbox"])
    page = browser.new_page(viewport={"width": 1440, "height": 1080})
    errors = []
    page.on("pageerror", lambda e: errors.append(str(e)))
    page.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
    page.on("response", lambda r: errors.append(r.url) if r.status >= 400 else None)
    page.goto(base)
    expect(page.get_by_role("heading", level=1)).to_contain_text("can take")
    page.keyboard.press("Tab")
    expect(page.get_by_text("Skip to content", exact=True)).to_be_focused()
    page.get_by_role("searchbox").fill("20KE")
    page.get_by_role("button", name="Find a model").click()
    expect(page.locator("#count")).to_have_text("1 model")
    expect(page.locator("[data-card]:visible h3")).to_have_text("ThinkPad X280")
    page.get_by_role("searchbox").fill("T14 Gen 2 AMD")
    expect(page.locator("#empty")).to_be_visible()
    page.get_by_role("button", name="Reset filters").click()
    expect(page.get_by_role("searchbox")).to_be_focused()
    expect(page.locator("#count")).to_have_text("6 models")
    page.get_by_label("RAM sockets").select_option("soldered")
    expect(page.locator("#count")).to_have_text("1 model")
    page.get_by_label("Storage format or interface").select_option("SATA")
    expect(page.locator("#count")).to_have_text("1 model")
    page.get_by_label("Storage format or interface").select_option("M.2 2280")
    expect(page.locator("#count")).to_have_text("0 models")
    page.get_by_role("button", name="Reset filters").click()
    for model in ("T480", "X280", "T14 Gen 2 (Intel)"):
        page.get_by_role("button", name=f"Compare ThinkPad {model}", exact=True).click()
    page.get_by_role("button", name="Compare ThinkPad T490", exact=True).click()
    expect(page.get_by_role("link", name="Open comparison")).to_be_focused()
    page.get_by_role("link", name="Open comparison").click()
    expect(page.locator("#compare-count")).to_contain_text("3 of 3")
    expect(page.locator("table thead th")).to_have_count(4)
    expect(page.get_by_text("48 GB · 16 GB onboard", exact=False)).to_be_visible()
    expect(page.get_by_role("button", name="Add model")).to_be_disabled()
    for model, count in (("T480", 2), ("X280", 1), ("T14 Gen 2 (Intel)", 0)):
        page.get_by_role("button", name=f"Remove ThinkPad {model}", exact=True).click()
        expect(page.locator("#compare-count")).to_have_text(f"{count} of 3 models selected")
    page.get_by_label("Add a model").select_option("thinkpad-t490")
    page.get_by_role("button", name="Add model").click()
    expect(page.locator("table thead th")).to_have_count(2)
    page.get_by_role("link", name="ThinkPad T490").click()
    page.get_by_role("button", name="Save ThinkPad T490").click()
    page.reload()
    expect(page.get_by_role("button", name="Save ThinkPad T490")).to_have_attribute("aria-pressed","true")
    page.locator("nav").get_by_role("link", name="Saved", exact=True).click()
    expect(page.locator("#saved-count")).to_have_text("1 saved model")
    page.get_by_role("button",name="Clear saved models").click()
    expect(page.locator("#saved-empty")).to_be_visible()
    page.reload()
    expect(page.locator("#saved-empty")).to_be_visible()

    page.set_viewport_size({"width": 360, "height": 800})
    page.goto(base + "/compare/index.html?models=thinkpad-t480,thinkpad-x280,thinkpad-t14-gen-2-intel,invalid,thinkpad-t490")
    expect(page.locator("table thead th")).to_have_count(4)
    region = page.get_by_role("region", name="Model comparison table")
    assert region.evaluate("(r) => r.scrollWidth > r.clientWidth")
    assert page.evaluate("document.documentElement.scrollWidth === innerWidth")
    region.focus()
    page.keyboard.press("ArrowRight")
    page.wait_for_function("document.activeElement.scrollLeft > 0")
    page.get_by_role("link", name="ThinkPad T14 Gen 2 (Intel)").click()
    expect(page.get_by_role("heading", name="ThinkPad T14 Gen 2 (Intel)")).to_be_visible()
    assert page.evaluate("document.documentElement.scrollWidth === innerWidth")
    page.evaluate("Object.defineProperty(navigator,'clipboard',{value:undefined})")
    page.get_by_role("button", name="Copy model link").click()
    url = page.get_by_role("textbox", name="Copy this model URL")
    expect(url).to_be_focused()
    assert url.input_value().endswith("/models/thinkpad-t14-gen-2-intel/index.html")
    page.goto(url.input_value())
    expect(page.get_by_role("heading", name="ThinkPad T14 Gen 2 (Intel)")).to_be_visible()
    page.evaluate("window.print = () => { window.printOpened = true }")
    page.get_by_role("button", name="Open print dialog").click()
    assert page.evaluate("window.printOpened")
    page.emulate_media(media="print")
    expect(page.locator(".detail-actions")).to_be_hidden()
    expect(page.get_by_text("Lenovo Product Specifications Reference", exact=True)).to_be_visible()
    pdf = Path(tmp) / "summary.pdf"
    page.pdf(path=pdf)
    if os.getenv("ATLAS_PRINT_PDF"):
        Path(os.environ["ATLAS_PRINT_PDF"]).write_bytes(pdf.read_bytes())
    assert not errors, errors

    context = browser.new_context(java_script_enabled=False)
    static = context.new_page()
    static.goto(base + "/models/thinkpad-x280/index.html")
    expect(static.get_by_text("Fully soldered memory.", exact=False).first).to_be_visible()
    expect(static.get_by_role("heading", name="Manufacturer sources")).to_be_visible()

    blocked = browser.new_page()
    blocked.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw new Error('blocked')}})")
    blocked.goto(base + "/catalogue/index.html")
    blocked.get_by_role("button", name="Save ThinkPad T480", exact=True).click()
    expect(blocked.locator("#announce")).to_contain_text("Browser storage is unavailable")
    expect(blocked.get_by_role("button", name="Save ThinkPad T480", exact=True)).to_have_attribute("aria-pressed","true")
    blocked.get_by_role("button", name="Compare ThinkPad T480", exact=True).click()
    blocked.get_by_role("link", name="Open comparison").click()
    expect(blocked.locator("#compare-count")).to_have_text("1 of 3 models selected")
    browser.close()
print("Chromium desktop/mobile workflows, keyboard, print, no-JS and storage fallback passed.")
